#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""R3-6 批3 · 简繁显示层转换表生成器。

数据源＝zhconv 1.4.3（BSD 3-Clause，数据承 OpenCC/国家标准简繁对照）的 zhcdict.json，
**只在生成期使用**，运行时零依赖（不引 Python/不引第三方包，App 仍离线）。

产出 `assets/read_s2t/s2t.json`：
  chars/to  —— 平行字符串的逐字映射（只收「会变」的字，繁→简是一对多归一，天然等长）；
  phr       —— 短语择字表，仅收「与逐字转换结果不同」且**源/目标等长**的条目
               （等长是硬约束：显示层转换不许改字符数，否则划线/书摘/链接偏移全部错位）。

用法（本机 python 可能是商店桩程序，务必用全路径）：
  D:/app_workplace/python3.11/python.exe tools/reader/gen_s2t.py <zhconv 解包目录>
例：… tools/reader/gen_s2t.py /tmp/s2tpkg/zhconv-1.4.3
"""
import json
import sys
import os

sys.path.insert(0, os.path.abspath(sys.argv[1]))
from zhconv import convert  # noqa: E402

SRC = os.path.join(sys.argv[1], "zhconv", "zhcdict.json")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                   "assets", "read_s2t", "s2t.json")


def u16(s):
    """UTF-16 码元数＝Dart String.length。偏移红线按码元算，不按「字数」：
    扩展 B 区汉字（如 U+23336）Python len() 是 1，Dart 是 2 —— 收进表里就会
    让划线/书摘/链接命中的下标全体位移，正是本批要防的假等长。"""
    return len(s.encode("utf-16-le")) // 2

# 逐字表覆盖范围：CJK 基本区 + 扩展 A + 兼容表意文字 + 常用标点（只留会变的）。
RANGES = [(0x4E00, 0x9FFF), (0x3400, 0x4DBF), (0xF900, 0xFAFF)]


def char_map(loc):
    src, dst = [], []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            out = convert(ch, loc)
            if u16(out) == 1 and out != ch:  # 码元不等的对子一律不收（见 u16 注释）
                src.append(ch)
                dst.append(out)
    return "".join(src), "".join(dst)


DICTS = ["zh2Hant", "zh2Hans", "zh2TW", "zh2HK", "zh2CN", "zh2SG"]


def candidates(target):
    """目标方向的候选词全集。

    zhconv 的 zh-hant / zh-hans 是**多档合并**（TW/HK/CN 都会参与择字），只读
    zh2Hant 一本会漏掉像「头发→頭髮」这类只在合并链里生效的择字——库本身转得对，
    我们的表却缺行，运行时就退回逐字（頭發）。所以候选＝所有字典的键，
    再加上各字典值归一到目标侧书写面的形态；是否收录一律**用库现算**判定。
    """
    d = json.load(open(SRC, encoding="utf-8"))
    loc = "zh-hant" if target == "hant" else "zh-hans"
    opp = "zh-hans" if target == "hant" else "zh-hant"
    cand = set()
    for name in DICTS:
        for k, v in d[name].items():
            cand.add(k)
            cand.add(convert(v, opp))
    return {w for w in cand if len(w) >= 2}


def phrase_map(target):
    """择字短语表：只收「库的结果 ≠ 逐字兜底的结果」且两侧码元等长的条目。"""
    loc = "zh-hant" if target == "hant" else "zh-hans"
    kept = []
    for w in candidates(target):
        v = convert(w, loc)
        if u16(v) != u16(w):
            continue  # 变长（按码元）一律不收——偏移红线
        naive = "".join(convert(c, loc) for c in w)
        if v != naive:
            kept.append((w, v))
    kept.sort(key=lambda x: (-len(x[0]), x[0]))
    return kept


def build(loc, target):
    s, t = char_map(loc)
    ph = phrase_map(target)
    return {"chars": s, "to": t, "phr": [f"{k}|{v}" for k, v in ph]}


def main():
    data = {
        "ver": 2,
        "src": "zhconv 1.4.3 zhcdict.json (BSD-3) · generated by tools/reader/gen_s2t.py",
        "s2t": build("zh-hant", "hant"),
        "t2s": build("zh-hans", "hans"),
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    print("chars s2t=%d t2s=%d · phr s2t=%d t2s=%d" % (
        len(data["s2t"]["chars"]), len(data["t2s"]["chars"]),
        len(data["s2t"]["phr"]), len(data["t2s"]["phr"])))
    print("max phrase len: s2t=%d t2s=%d" % (
        max((len(p.split("|")[0]) for p in data["s2t"]["phr"]), default=0),
        max((len(p.split("|")[0]) for p in data["t2s"]["phr"]), default=0)))
    print("bytes=%d -> %s" % (os.path.getsize(OUT), OUT))


if __name__ == "__main__":
    main()
