const fs=require('fs');
const f='lib/features/read/presentation/reader_page.dart';
let src=fs.readFileSync(f,'utf8');
const start='  /// 前扩/后扩：按句推进；本段句子用尽后整段吞/吐，再跨段。\n';
const i=src.indexOf(start);
if(i<0) throw new Error('未找到 _growSel 起点');
const j=src.indexOf('  void _clearSel()', i);
if(j<0) throw new Error('未找到 _clearSel 终点');
const removed=src.slice(i,j);
if(!removed.includes('_growSel')||!removed.includes('_sentenceAt')) throw new Error('待删块缺少锚点');
if(removed.length>2400) throw new Error('待删块异常大: '+removed.length);
src=src.slice(0,i)+src.slice(j);
const before=src.length;
src=src.replace('if (_sel != null) _selOverlay(size),','if (_sel != null) ..._selLayer(size),');
if(src.length===before) throw new Error('调用点未替换');
if(src.includes('_growSel')) throw new Error('仍有 _growSel 残留');
src=src.replace('（长按默认命中一句，前扩/后扩按句走）','（长按默认命中一句 · 轮5① 扩选改为首尾手柄拖动）');
fs.writeFileSync(f,src,'utf8');
console.log('ok · removed '+removed.length+' chars');
